// Generate supabase/migrations/20261023_pgc_seed_content.sql from the pages
// as they are served. Uses the same assets/js/content.js the public site and
// the portal use, so what goes into the database is exactly what the renderer
// reads back out of it — no hand-transcribed copy.
//
//   python3 -m http.server 8765 &                      # from the repo root
//   node tools/dump_content.mjs                        # writes the migration
//   PLAYWRIGHT_MODULE=… CHROME_PATH=… BASE=… override the defaults
import fs from "node:fs";
import path from "node:path";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "/opt/node22/lib/node_modules/playwright/index.mjs");
const BASE = process.env.BASE || "http://127.0.0.1:8765";
const OUT = process.env.OUT || path.join(process.cwd(), "supabase", "migrations", "20261023_pgc_seed_content.sql");

const PAGES = [
  { slug: "home", path: "/", nav_label: "Home" },
  { slug: "thesis", path: "/thesis/", nav_label: "Investment Thesis" },
  { slug: "investors", path: "/investors/", nav_label: "For Investors" },
  { slug: "founders", path: "/founders/", nav_label: "Founders & Companies" },
  { slug: "team", path: "/team/", nav_label: "Team" },
  { slug: "contact", path: "/contact/", nav_label: "Contact" },
];
const SETTINGS = [
  { key: "footer_tagline", label: "Footer tagline", selector: "[data-pgc-setting=footer_tagline]" },
  { key: "footer_disclaimer", label: "Footer disclosure", selector: "[data-pgc-setting=footer_disclaimer]" },
  { key: "contact_email", label: "Contact email address", selector: "[data-pgc-setting=contact_email]" },
];

const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || "/opt/pw-browsers/chromium", args: ["--no-sandbox"] });
const page = await browser.newPage();
await page.addInitScript(() => { window.__PGC_NO_HYDRATE = true; });
await page.route(/fonts\.googleapis|fonts\.gstatic|jsdelivr/, (r) => r.fulfill({ status: 200, contentType: "text/plain", body: "" }));

const pages = []; let team = []; const settings = [];
for (const def of PAGES) {
  await page.goto(BASE + def.path, { waitUntil: "load" });
  const data = await page.evaluate(async () => {
    const m = await import("/assets/js/content.js");
    const main = document.querySelector("[data-pgc-page]");
    const meta = document.querySelector('meta[name="description"]');
    return {
      title: document.title,
      meta_description: meta ? meta.getAttribute("content") : null,
      page: m.readPage(main),
      team: Array.from(main.querySelectorAll("[data-pgc-team]")).flatMap((g) => m.readTeamGrid(g)),
      settings: Array.from(document.querySelectorAll("[data-pgc-setting]")).map((el) => ({ key: el.dataset.pgcSetting, value: el.textContent.trim() })),
    };
  });
  pages.push({ def, ...data });
  if (data.team.length) team = team.concat(data.team);
  data.settings.forEach((s) => { if (!settings.some((x) => x.key === s.key)) settings.push(s); });
}
await browser.close();

/* ---- SQL ---- */
const q = (v) => (v == null || v === "" ? "null" : "'" + String(v).replace(/'/g, "''") + "'");
const j = (v) => "'" + JSON.stringify(v == null ? [] : v).replace(/'/g, "''") + "'::jsonb";
let sql = `-- ============================================================================
-- Proving Ground Capital (PGC) — initial content, read from the live pages.
-- Generated by tools/dump_content.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand;
-- re-run the tool after changing the HTML in this repository.
--
-- Apply after 20261023_pgc_site_content.sql (and the bucket migration). Optional: without it, the portal offers "Start from the live
-- page" for each page, which creates the same rows as drafts.
--
-- Every row is inserted as PUBLISHED, so applying this changes nothing for
-- visitors: the database says exactly what the repository already says, and
-- from then on edits made in the portal take over. Existing rows (by page
-- slug / section key / team member name / setting key) are left alone, so the
-- file is safe to re-run.
-- ============================================================================
set lock_timeout = '15s';
begin;
select set_config('pgc.skip_revision', 'on', true);  -- the seed is not a user's edit

`;
pages.forEach((p, pi) => {
  sql += `-- ---------------- ${p.def.path} ----------------\n`;
  sql += `insert into public.pgc_pages (slug, path, title, nav_label, meta_description, sort_order, published, review_state)\n`;
  sql += `values (${q(p.def.slug)}, ${q(p.def.path)}, ${q(p.title)}, ${q(p.def.nav_label)}, ${q(p.meta_description)}, ${(pi + 1) * 10}, true, 'draft')\n`;
  sql += `on conflict (slug) do nothing;\n\n`;
  p.page.sections.forEach((s) => {
    sql += `insert into public.pgc_sections (page_id, section_key, kind, eyebrow, heading, heading_accent, kicker, lead, note, bullets, items, band, sort_order, published, review_state)\n`;
    sql += `select id, ${q(s.section_key)}, ${q(s.kind)}, ${q(s.eyebrow)}, ${q(s.heading)}, ${q(s.heading_accent)}, ${q(s.kicker)}, ${q(s.lead)}, ${q(s.note)}, ${j(s.bullets)}, ${j(s.items)}, ${q(s.band)}, ${s.sort_order}, true, 'draft'\n`;
    sql += `  from public.pgc_pages where slug = ${q(p.def.slug)}\n`;
    sql += `on conflict (page_id, section_key) do nothing;\n\n`;
  });
});
sql += `-- ---------------- team ----------------\n`;
team.forEach((t) => {
  sql += `insert into public.pgc_team (name, role, bio, photo_url, photo_alt, linkedin_url, email, team_group, sort_order, published, review_state)\n`;
  sql += `select ${q(t.name)}, ${q(t.role)}, ${q(t.bio)}, ${q(t.photo_url)}, ${q(t.photo_alt)}, ${q(t.linkedin_url)}, ${q(t.email)}, ${q(t.team_group)}, ${t.sort_order}, true, 'draft'\n`;
  sql += `where not exists (select 1 from public.pgc_team where name = ${q(t.name)});\n\n`;
});
sql += `-- ---------------- settings ----------------\n`;
SETTINGS.forEach((d) => {
  const v = settings.find((s) => s.key === d.key);
  sql += `insert into public.pgc_settings (key, label, value, published, review_state)\nvalues (${q(d.key)}, ${q(d.label)}, ${q(v ? v.value : null)}, true, 'draft')\non conflict (key) do nothing;\n\n`;
});
sql += `commit;\n`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, sql);
console.log(JSON.stringify({ out: OUT, pages: pages.map((p) => ({ slug: p.def.slug, sections: p.page.sections.map((s) => s.section_key) })), team: team.map((t) => t.name), settings: settings.map((s) => s.key) }, null, 1));
