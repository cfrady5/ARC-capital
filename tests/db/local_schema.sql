-- Local stand-in for the parts of ARI's production schema that the PGC
-- migrations depend on (as of 2026-10-22): the auth stubs, employees,
-- employee_access with its module check, the access helpers, the shared
-- content_revisions table and a plain storage schema.
--
-- Usage (see tests/README.md):
--   psql -v ON_ERROR_STOP=1 -d pgc_test -f tests/db/local_schema.sql
--   psql -v ON_ERROR_STOP=1 -d pgc_test -f supabase/migrations/20261023_pgc_site_content.sql
--   psql -v ON_ERROR_STOP=1 -d pgc_test -f supabase/migrations/20261023_pgc_media_bucket.sql
--   psql -v ON_ERROR_STOP=1 -d pgc_test -f tests/db/rls_tests.sql
--
-- Anything defined here mirrors ARI's definitions (20260922_workspaces_access_model.sql
-- and tests/db/local_schema.sql in cfrady5/ARI); it is a fixture, not a
-- migration, and is never applied to production.

create extension if not exists pgcrypto;
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin bypassrls; end if;
end $$;

create schema if not exists auth;
create schema if not exists storage;
grant usage on schema public, auth, storage to anon, authenticated, service_role;

-- auth.jwt() / auth.uid() read request.jwt.claims, the way PostgREST sets it.
create table if not exists auth.users (
  id uuid primary key default gen_random_uuid(),
  email text, email_confirmed_at timestamptz, created_at timestamptz not null default now()
);
create or replace function auth.jwt() returns jsonb language sql stable as $$
  select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb; $$;
create or replace function auth.uid() returns uuid language sql stable as $$
  select nullif(auth.jwt() ->> 'sub', '')::uuid; $$;
create or replace function auth.role() returns text language sql stable as $$ select auth.jwt() ->> 'role'; $$;

-- ---------------- ARI tables the PGC tables lean on ----------------
create table public.employees (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  full_name text,
  avatar_url text,
  role text not null default 'employee' check (role in ('employee', 'hr', 'admin')),
  status text not null default 'active' check (status in ('active', 'suspended')),
  team_id uuid,
  created_at timestamptz not null default now()
);
create table public.employee_access (
  id uuid primary key default gen_random_uuid(),
  employee_id uuid not null references public.employees (id) on delete cascade,
  module text not null,
  level text not null check (level in ('contributor', 'publisher', 'access')),
  granted_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (employee_id, module)
);
-- The production constraint as 20261022_documents_access.sql left it. The PGC
-- migration must replace it with the same list plus 'pgc'.
alter table public.employee_access add constraint employee_access_module_check
  check (module in ('pages', 'newsroom', 'calendar', 'evsites', 'messages', 'newsletter', 'babble', 'pulse', 'documents'));
create table public.content_revisions (
  id bigint generated by default as identity primary key,
  table_name text not null, record_id uuid not null, operation text not null,
  snapshot jsonb not null, label text, changed_by text,
  changed_at timestamptz not null default now(),
  check (operation = any (array['insert', 'update', 'delete', 'restore']))
);
-- An ARI table that must stay out of reach of pgc_restore_revision().
create table public.posts (id uuid primary key default gen_random_uuid(), title text, published boolean not null default false);
alter table public.employees enable row level security;
alter table public.employee_access enable row level security;
alter table public.content_revisions enable row level security;
alter table public.posts enable row level security;
grant select, insert, update, delete on all tables in schema public to authenticated, service_role;
alter default privileges in schema public grant select, insert, update, delete on tables to authenticated, service_role;

-- ---------------- ARI helpers (verbatim semantics) ----------------
create or replace function public.jwt_email() returns text
language sql stable as $$ select lower(coalesce(auth.jwt() ->> 'email', '')); $$;
create or replace function public.is_server() returns boolean
language sql stable as $$ select coalesce(auth.jwt() ->> 'role', '') in ('', 'service_role'); $$;
create or replace function public.is_employee() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.employees where lower(email) = public.jwt_email() and status = 'active'); $$;
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.employees where lower(email) = public.jwt_email() and status = 'active' and role = 'admin'); $$;
create or replace function public.has_access(p_module text, p_level text) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_admin() or exists (
    select 1 from public.employee_access a join public.employees e on e.id = a.employee_id
     where lower(e.email) = public.jwt_email() and e.status = 'active' and a.module = p_module
       and case p_level when 'contributor' then a.level in ('contributor', 'publisher')
                        when 'publisher' then a.level = 'publisher'
                        when 'access' then a.level = 'access' else false end); $$;
create or replace function public.can_edit(p_module text) returns boolean
language sql stable as $$ select public.has_access(p_module, 'contributor'); $$;
create or replace function public.can_publish(p_module text) returns boolean
language sql stable as $$ select public.has_access(p_module, 'publisher'); $$;
create or replace function public.is_comms() returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_admin() or exists (
    select 1 from public.employee_access a join public.employees e on e.id = a.employee_id
     where lower(e.email) = public.jwt_email() and e.status = 'active' and a.module <> 'messages'); $$;
create or replace function public.my_access() returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce((
    select jsonb_build_object('email', e.email, 'full_name', e.full_name, 'avatar_url', e.avatar_url, 'role', e.role, 'status', e.status,
      'modules', coalesce((select jsonb_object_agg(a.module, a.level) from public.employee_access a where a.employee_id = e.id), '{}'::jsonb))
    from public.employees e where lower(e.email) = public.jwt_email() limit 1), 'null'::jsonb); $$;

create policy employees_select on public.employees for select using (public.is_employee());
create policy employee_access_select on public.employee_access for select
  using (public.is_admin() or employee_id in (select id from public.employees where lower(email) = public.jwt_email()));
create policy revisions_select on public.content_revisions for select using (public.is_comms());

-- ---------------- storage, as plain tables ----------------
create table storage.buckets (
  id text primary key, name text not null, public boolean default false,
  file_size_limit bigint, allowed_mime_types text[], created_at timestamptz default now()
);
create table storage.objects (
  id uuid primary key default gen_random_uuid(),
  bucket_id text references storage.buckets (id), name text, owner uuid,
  metadata jsonb, created_at timestamptz default now()
);
alter table storage.objects enable row level security;
grant select, insert, update, delete on storage.objects to anon, authenticated, service_role;
grant select on storage.buckets to anon, authenticated, service_role;
